let seq = 0;
const msg = (type, body, at, extra = {}) => ({
  id: `m_${++seq}`,
  type,
  body,
  createdAt: at,
  ...extra,
});
const incoming = (body, at, extra) => msg("incoming", body, at, extra);
const outgoing = (authorId, body, at, status = "read", extra) =>
  msg("outgoing", body, at, { authorId, status, ...extra });
const note = (authorId, body, at) => msg("note", body, at, { authorId });
const event = (body, at) => msg("event", body, at);

